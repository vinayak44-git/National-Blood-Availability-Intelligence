function applyGlobalLanguage(lang) {
    const dict = RAKTSETU_I18N[lang] || RAKTSETU_I18N.en;
    localStorage.setItem('raktsetu_lang', lang);

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            if (el.tagName === 'INPUT' && el.type === 'button') {
                el.value = dict[key];
            } else {
                el.textContent = dict[key];
            }
        }
    });
}

window.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('raktsetu_lang') || 'en';
    const selectors = document.querySelectorAll('.lang-selector');
    selectors.forEach(s => {
        s.value = savedLang;
        s.addEventListener('change', (e) => applyGlobalLanguage(e.target.value));
    });
    applyGlobalLanguage(savedLang);
});
